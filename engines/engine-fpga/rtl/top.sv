// pwdcrack FPGA top level.
//
// # What this design contains
//
// Nine verified blocks, and nothing else:
//
//   md5_core          pipelined, one block per cycle
//   md4_core          iterative, 48 rounds
//   sha1_core         iterative, 80 rounds
//   sha256_core       iterative, 64 rounds
//   sha512_core       iterative, 80 rounds, 64 bit datapath
//   sha384_core       a wrapper over sha512_core with a different initial value
//   ripemd160_core    iterative, 80 rounds, two parallel lines
//   crc32_accel       byte at a time, for the host protocol
//   ntlm_core         a wrapper over md4_core that builds the UTF-16-LE block
//
// `scripts/simulate.sh` reports each one passing against vectors generated by
// scripts/gen-rtl-vectors.py. The inventory it prints is the authority; this
// comment is kept in step with it by hand because a comment cannot run.
//
// # What is deliberately absent
//
// Every other file in `rtl/cores` carries a banner saying it is unverified, and
// none of them is instantiated here. P8.2.10 requires that the design contain
// only verified blocks, and the point is not tidiness: an unverified core in a
// bitstream is a core whose digest is a plausible wrong answer, and a cracker
// that reports a wrong match is worse than one that reports nothing.
//
// The absent ones, and what each would need, are listed in docs/PHASE8_STATUS.md.
//
// # The mux
//
// One hash interface with a four bit selector rather than eight separate
// interfaces. The cores disagree about digest width, so the widest is on the
// outside and each core is given the low bits of it, which is exactly what its
// own port would carry. A caller that selects SHA-256 and reads the low 256 bits
// of `digest_out` gets the SHA-256 digest; the upper bits are that core's stale
// output, which is why `tb_top.sv` compares the width the selector implies and
// not the whole register.
//
// The CRC path is separate rather than muxed: it is byte at a time, has no
// chaining state, and shares nothing with the hash cores.
//
// # No PCIe
//
// The earlier version of this file declared a PCIe and DDR interface. There is
// no FPGA, no vendor toolchain and no board in this repository, so nothing about
// such an interface could be compiled, let alone verified. Writing those ports
// produced a file that looked like a design and could not elaborate, which is
// worse than not having them. The transport in `src/protocol.rs` describes the
// packets; nothing here claims to produce them.

module pwdcrack_top #(
    // Which hash core `hash_sel` selects. Declared as parameters of the wrapper
    // functions below and mirrored in the generator that writes the vectors, so
    // a change to the encoding changes both sides or neither.
    parameter int SEL_MD5       = 4'h0,
    parameter int SEL_MD4       = 4'h1,
    parameter int SEL_SHA1      = 4'h2,
    parameter int SEL_SHA256    = 4'h3,
    parameter int SEL_SHA512    = 4'h4,
    parameter int SEL_SHA384    = 4'h5,
    parameter int SEL_RIPEMD160 = 4'h6
) (
    input  logic          clk,
    input  logic          rst_n,

    // Hash path.
    input  logic [3:0]    hash_sel,
    input  logic          valid,
    output logic          ready,
    input  logic [1023:0] msg_blk,
    input  logic [511:0]  state_in,
    output logic [511:0]  digest_out,
    output logic          done,

    // CRC path, independent of the hash path.
    input  logic          crc_init,
    input  logic          crc_valid,
    input  logic          crc_byte_last,
    input  logic [7:0]    crc_byte_in,
    output logic [31:0]   crc_out,
    output logic          crc_done
);

    // The selector picks which core sees `valid`, and the outputs are muxed.
    //
    // Gating the input matters, and the top level testbench is what found it.
    // With every core tied to `valid`, an unselected core starts a block it will
    // never report. If that block is still running when the caller selects it,
    // the new block is dropped, because an iterative core ignores `valid` while
    // busy, and the caller gets the digest of the discarded one. The symptom is
    // a core that passes every one of its own vectors and then fails through the
    // mux, which is why the top testbench exists at all.
    //
    // `ready` and `done` are muxed rather than wired together for the same
    // reason: a completion from a core that was selected a moment ago must not be
    // reported against the one selected now.
    //
    // SHA-384 shares nothing with SHA-512 at this level: `sha384_core` is a
    // wrapper that contains its own `sha512_core` instance. They are separate
    // cores here, which is one 82 cycle pipeline more than a design that routed
    // SHA-384 through the SHA-512 selector would need, and it keeps the two
    // algorithms from blocking each other's blocks.

    logic [1023:0] core_blk;
    logic [511:0]  core_state;

    // A digest vector per core, not one shared vector.
    //
    // Sharing and slicing does not work: the 128 bit cores both drive bits
    // [127:0], so two module outputs would drive the same net. Icarus reports
    // "unresolved net core_digest cannot have multiple drivers", which is the
    // simulator being helpful; a synthesis tool may instead report nothing and
    // produce a net with undefined resolution. Separate vectors cost 2 kilobits
    // of registers that are already there inside the cores.
    logic [511:0]  md5_digest;
    logic [511:0]  md4_digest;
    logic [511:0]  sha1_digest;
    logic [511:0]  sha256_digest;
    logic [511:0]  sha512_digest;
    logic [383:0]  sha384_digest;
    logic [511:0]  ripemd160_digest;

    // One ready and one done per core.
    //
    // They cannot share a single net: seven module outputs driving one wire is a
    // multiple driver net, which is either an error or, with a wired-OR reading,
    // reports ready while some selected core is busy. The previous version of
    // this file had `core_ready` and `core_done` as single nets, which is
    // exactly that.
    logic [6:0]    core_ready;
    logic [6:0]    core_done;
    logic [6:0]    core_valid;

    // Index of the selected core. Declared before `core_valid` uses it.
    logic [2:0] sel_index;

    // One valid per core, from the single external `valid` and the selector.
    always_comb begin
        for (int i = 0; i < 7; i = i + 1)
            core_valid[i] = valid & (sel_index == i[2:0]);
    end

    assign core_blk   = msg_blk;
    assign core_state = state_in;

    // The wide cores take the block whole; the 512 bit cores take its low half,
    // which is word 0 at the low bits in both conventions.
    md5_core u_md5 (
        .clk (clk), .rst_n (rst_n), .valid (core_valid[0]), .ready (core_ready[0]),
        .msg_blk (core_blk[511:0]), .state_in (core_state[127:0]),
        .digest_out (md5_digest[127:0]), .done (core_done[0])
    );

    md4_core u_md4 (
        .clk (clk), .rst_n (rst_n), .valid (core_valid[1]), .ready (core_ready[1]),
        .msg_blk (core_blk[511:0]), .state_in (core_state[127:0]),
        .digest_out (md4_digest[127:0]), .done (core_done[1])
    );

    sha1_core u_sha1 (
        .clk (clk), .rst_n (rst_n), .valid (core_valid[2]), .ready (core_ready[2]),
        .msg_blk (core_blk[511:0]), .state_in (core_state[159:0]),
        .digest_out (sha1_digest[159:0]), .done (core_done[2])
    );

    sha256_core u_sha256 (
        .clk (clk), .rst_n (rst_n), .valid (core_valid[3]), .ready (core_ready[3]),
        .msg_blk (core_blk[511:0]), .state_in (core_state[255:0]),
        .digest_out (sha256_digest[255:0]), .done (core_done[3])
    );

    sha512_core u_sha512 (
        .clk (clk), .rst_n (rst_n), .valid (core_valid[4]), .ready (core_ready[4]),
        .msg_blk (core_blk), .state_in (core_state),
        .digest_out (sha512_digest), .done (core_done[4])
    );

    sha384_core u_sha384 (
        .clk (clk), .rst_n (rst_n), .valid (core_valid[5]), .ready (core_ready[5]),
        .msg_blk (core_blk), .state_in (core_state[383:0]),
        .digest_out (sha384_digest), .done (core_done[5])
    );

    ripemd160_core u_ripemd160 (
        .clk (clk), .rst_n (rst_n), .valid (core_valid[6]), .ready (core_ready[6]),
        .msg_blk (core_blk[511:0]), .state_in (core_state[159:0]),
        .digest_out (ripemd160_digest[159:0]), .done (core_done[6])
    );

    // The index of the selected core, used to pick its `ready` and its `done`.
    // `always_comb`, not `always @*`: an `always @*` block does not run at time
    // zero unless one of its inputs changes, so a selector that is already at
    // its initial value never assigns and every mux output stays X. Icarus
    // warns "constant selects in always_* processes are not currently supported"
    // and includes every bit in the sensitivity list instead, which for a
    // multiplexer is harmless.
    always_comb begin
        case (hash_sel)
            SEL_MD5:       sel_index = 3'd0;
            SEL_MD4:       sel_index = 3'd1;
            SEL_SHA1:      sel_index = 3'd2;
            SEL_SHA256:    sel_index = 3'd3;
            SEL_SHA512:    sel_index = 3'd4;
            SEL_SHA384:    sel_index = 3'd5;
            default:       sel_index = 3'd6;
        endcase
    end

    assign ready = core_ready[sel_index];

    // Each branch presents only the digest width the selected algorithm has, so
    // a caller reading more than the algorithm produces reads zeros rather than
    // another core's stale output.
    always_comb begin
        case (hash_sel)
            SEL_MD5:       digest_out = {{384{1'b0}}, md5_digest[127:0]};
            SEL_MD4:       digest_out = {{384{1'b0}}, md4_digest[127:0]};
            SEL_SHA1:      digest_out = {{352{1'b0}}, sha1_digest[159:0]};
            SEL_SHA256:    digest_out = {{256{1'b0}}, sha256_digest[255:0]};
            SEL_SHA512:    digest_out = sha512_digest;
            SEL_SHA384:    digest_out = {{128{1'b0}}, sha384_digest};
            default:       digest_out = {{352{1'b0}}, ripemd160_digest[159:0]};
        endcase
    end

    // `done` comes from the selected core, so a completion from a core that was
    // selected a moment ago is not reported against the one selected now.
    assign done = core_done[sel_index];

    crc32_accel u_crc (
        .clk (clk), .rst_n (rst_n),
        .crc_init (crc_init), .valid (crc_valid),
        .byte_last (crc_byte_last), .data_in (crc_byte_in),
        .crc_out (crc_out), .done (crc_done)
    );

endmodule