//! The cluster wire schema.
//!
//! # What this is
//!
//! A set of `Message` variants, and nothing else. The bytes that carry them, the
//! framing, the version byte and the integrity check live in [`crate::codec`].
//! Splitting them is deliberate: the schema is the thing that has to stay
//! compatible between a master and a worker built from different commits, and it
//! should be readable without also reading a CRC implementation.
//!
//! # Versioning
//!
//! Two version numbers are in play and they answer different questions.
//!
//! | Version | Guards | Where it is |
//! |---------|--------|-------------|
//! | framing version | the byte layout of a frame | [`crate::codec::FRAMING_VERSION`] |
//! | schema version | which `Message` variants exist and what they contain | [`SCHEMA_VERSION`] |
//!
//! Bump `SCHEMA_VERSION` when a variant is added, removed, or reshaped. Bump
//! `FRAMING_VERSION` when the header itself changes. A peer that disagrees on
//! either is refused with a message naming both numbers, rather than being fed a
//! payload that happens to decode into the wrong variant.
//!
//! The practical rule for adding a variant: append it, bump the schema, and do
//! not renumber or reorder anything. `bincode` encodes an enum variant by its
//! index, so inserting in the middle silently changes the meaning of every frame
//! in flight.
//!
//! # Why `f64` appears here
//!
//! `WorkerStats` and `WorkProgress` carry rates and temperatures as `f64`.
//! Floating point is fine for a displayed rate and wrong for an identity, so no
//! `f64` is ever used to decide which worker gets which work; the scheduler
//! compares *durations* derived from rates, and a tie falls back to a
//! deterministic ordering. See [`crate::scheduler`].

use serde::{Deserialize, Serialize};

use crate::wordlist::WordlistManifest;

/// The schema version this build speaks.
///
/// Sent in `Challenge` by the master and in `Handshake` by the worker, so each
/// side learns the other's number within the first two frames of a connection
/// instead of discovering a mismatch halfway through a work unit.
pub const SCHEMA_VERSION: u16 = 1;

/// One frame of the cluster protocol.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub enum Message {
    // ---- Liveness, both directions ----

    /// Liveness probe. Answered before admission, so a worker can check a master
    /// is reachable without holding the cluster token.
    Ping,
    Pong,

    // ---- Admission, master to worker ----

    /// The first frame the master sends on every connection.
    ///
    /// The nonce is generated by the master and is fresh per connection, which is
    /// what binds a `Authenticate` response to one session. It also carries the
    /// schema version, so a worker built against a different schema can refuse
    /// immediately and say why, rather than waiting for a frame it cannot decode.
    Challenge {
        /// Lowercase hex of a fresh nonce.
        nonce: String,
        /// The master's schema version.
        protocol_version: u16,
    },

    /// The worker's reply to a `Challenge`.
    ///
    /// `SHA-256(token || nonce)` over the nonce the master just sent. Bound to
    /// this connection, so a response captured from one session is worthless in
    /// another.
    Authenticate {
        /// Lowercase hex of the 32 byte digest.
        response: String,
    },

    /// Identity and capabilities, sent once the peer is admitted.
    Handshake {
        /// The worker's schema version, so the master can refuse a stale client
        /// with the same precision the worker refuses a stale master.
        protocol_version: u16,
        node_name: String,
        tier: String,
        caps: Capabilities,
    },

    // ---- Liveness, both directions ----

    /// Worker to master: "still here, here is what I have done".
    Heartbeat {
        node_name: String,
        stats: WorkerStats,
    },

    /// Master to worker: the heartbeat schedule the worker should follow.
    ///
    /// The master owns the schedule because it is the side that decides when a
    /// worker is dead. `next_heartbeat_ms` is the current backoff period: it is
    /// the base interval while heartbeats are arriving and doubles each time one
    /// is missed, which keeps a master that has lost the peer from queueing up a
    /// backlog of heartbeats against a dead socket.
    HeartbeatAck {
        /// Master wall clock in milliseconds since the Unix epoch.
        server_time_ms: u64,
        /// How long the worker should wait before its next heartbeat.
        next_heartbeat_ms: u64,
        /// How many heartbeats the master has now missed from this worker.
        missed: u32,
    },

    /// Worker to master: throughput for a batch in flight.
    ///
    /// This is the input to the weighted scheduler. Sending it per batch rather
    /// than only in `Heartbeat` matters when a single batch takes longer than the
    /// heartbeat interval, which is the normal case for a large chunk.
    WorkProgress {
        node_name: String,
        batch_id: u64,
        tested: u64,
        hashes_sec: f64,
    },

    // ---- Work, master to worker ----

    /// A chunk of a job's candidate keyspace.
    AssignWork {
        worker_id: u64,
        batch_id: u64,
        work: WorkUnit,
    },

    /// A wordlist the worker does not have to have on disk.
    ///
    /// Sent once per connection, before the first `AssignWork` that references
    /// it. Sending contents removes the master naming a path at all, which is
    /// the whole of P9.1.05's first option; the manifest is what lets the worker
    /// prove it received the bytes the master meant to send.
    Wordlist {
        manifest: WordlistManifest,
        words: Vec<String>,
    },

    /// Stop, with a reason, for a log line that says why.
    Shutdown {
        reason: String,
    },

    /// A refusal the peer should be able to read instead of guessing.
    ///
    /// Sent before the connection closes. A closed socket tells a worker nothing;
    /// this tells it whether it was throttled, refused for a stale schema, or
    /// caught sending a malformed frame.
    Error {
        code: ErrorCode,
        detail: String,
    },

    // ---- Work, worker to master ----

    /// Finished batch.
    ///
    /// `solved` is every target this worker has found, including ones found in
    /// earlier batches. The master uses it to stop building chunks around a hash
    /// that is already cracked, and it is idempotent so a requeued batch that
    /// runs twice cannot double count.
    Result {
        node_name: String,
        batch_id: u64,
        cracked: Vec<CrackedEntry>,
        solved: Vec<TargetHash>,
    },
}

/// Why the master refused something.
///
/// Values are explicit rather than free text so a log can be grouped by cause.
/// The `detail` carries the specifics, including the peer's address.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub enum ErrorCode {
    /// Too many handshake attempts from this address. See [`crate::ratelimit`].
    Throttled,
    /// No token, or the wrong one.
    NotAdmitted,
    /// The peer's schema or framing version does not match.
    VersionMismatch,
    /// The peer sent bytes that are not a valid frame.
    ProtocolViolation,
    /// The peer asked for a frame larger than the master will send.
    FrameTooLarge,
    /// A wordlist chunk referenced content the worker never received.
    WordlistMissing,
    /// The worker is not configured to open the requested path.
    WordlistRefused,
    /// The master is shutting down.
    ShuttingDown,
}

/// What a worker claims it can do.
///
/// Every field here is a claim. `WorkerStats` is what the worker actually
/// measured, and the master prefers it over anything in `Capabilities` when it
/// sizes a chunk, because a self reported core count is not a throughput.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct Capabilities {
    pub simd: String,
    pub gpu: bool,
    pub fpga: bool,
    pub max_threads: usize,
    pub ram_mb: u64,
}

/// What a worker measured while working.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct WorkerStats {
    pub hashes_sec: f64,
    pub total_cracked: u64,
    pub power_watts: f64,
    pub temperature_c: f64,
}

/// One cracked hash and its plaintext.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct CrackedEntry {
    pub hash: String,
    pub password: String,
    pub algorithm: String,
}

/// A hash the cluster is trying to crack.
#[derive(Debug, Clone, PartialEq, Eq, Hash, PartialOrd, Ord, Serialize, Deserialize)]
pub struct TargetHash {
    /// Canonical algorithm name, for example `MD5` or `NTLM`.
    pub hash_type: String,
    /// Lowercase hex of the digest.
    pub hash: String,
}

impl TargetHash {
    pub fn new(hash_type: impl Into<String>, hash: impl Into<String>) -> Self {
        TargetHash {
            hash_type: hash_type.into(),
            hash: hash.into().to_lowercase(),
        }
    }
}

/// A chunk of one job's candidate keyspace.
///
/// `keyspace_start` is inclusive and `keyspace_end` is exclusive, which is what
/// makes consecutive chunks concatenate without an off-by-one gap. The master
/// guarantees that the ranges it issues for a job are pairwise disjoint and
/// cover the whole keyspace exactly once; see [`crate::scheduler`].
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct WorkUnit {
    /// Which job this chunk belongs to. Several chunks of one job carry the same
    /// id, so the master can reassemble them for a checkpoint or a resume.
    pub job_id: u64,
    /// How to turn a candidate index into a candidate.
    pub attack_type: AttackType,
    /// The hashes this chunk should be tested against.
    ///
    /// A vector rather than a single hash because a cluster run against a hash
    /// file needs every node testing every hash; one hash per chunk would spend
    /// most of its time re-reading the same wordlist.
    pub targets: Vec<TargetHash>,
    pub keyspace_start: u64,
    pub keyspace_end: u64,
    /// The whole job's keyspace, not this chunk's.
    ///
    /// Sent so a worker can check that the attack it was given really does have
    /// the range the master thinks it has. Without it a worker cannot tell
    /// whether it is scanning the range it was asked for or a different one of
    /// the same length, and the only symptom would be a run that reports "not
    /// found" for a password that is in the wordlist.
    pub keyspace_total: u64,
}

impl WorkUnit {
    /// Candidates in this chunk. `0` for an empty chunk, which is never issued.
    pub fn total_size(&self) -> u64 {
        self.keyspace_end.saturating_sub(self.keyspace_start)
    }
}

/// What the master tells a worker to do about one chunk.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub enum AttackType {
    /// Read a wordlist from a path the worker was granted locally.
    ///
    /// The path is validated against the worker's own `--wordlist-dir` grant
    /// before it is opened, so a master cannot widen the grant. See
    /// [`crate::wordlist`].
    Dictionary {
        wordlist_path: String,
        rules: Vec<String>,
    },

    /// Use a wordlist the master shipped in a `Wordlist` frame.
    ///
    /// The identifier is the SHA-256 of the contents, which is also the cache
    /// key, so a worker cannot silently use one wordlist where another was
    /// meant.
    Inline {
        /// SHA-256 of the wordlist contents, lowercase hex.
        sha256: String,
        rules: Vec<String>,
    },

    /// Enumerate a mask, mapping the candidate index onto the mask positions.
    BruteForce {
        mask: String,
    },

    /// Concatenate pairs from two lists.
    Combinator {
        left_words: Vec<String>,
        right_words: Vec<String>,
    },
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Every variant must survive a round trip through the serialiser. A new
    /// variant that is added but never constructed is exactly how a schema gap
    /// gets shipped, and the gap is only visible on the wire.
    fn samples() -> Vec<Message> {
        vec![
            Message::Ping,
            Message::Pong,
            Message::Challenge {
                nonce: "00ff".to_string(),
                protocol_version: SCHEMA_VERSION,
            },
            Message::Authenticate {
                response: "ab".to_string(),
            },
            Message::Handshake {
                protocol_version: SCHEMA_VERSION,
                node_name: "n1".to_string(),
                tier: "x86_64".to_string(),
                caps: Capabilities {
                    simd: "avx2".to_string(),
                    gpu: true,
                    fpga: false,
                    max_threads: 8,
                    ram_mb: 16384,
                },
            },
            Message::Heartbeat {
                node_name: "n1".to_string(),
                stats: WorkerStats {
                    hashes_sec: 1.5,
                    total_cracked: 2,
                    power_watts: 65.0,
                    temperature_c: 55.5,
                },
            },
            Message::HeartbeatAck {
                server_time_ms: 1_700_000_000_000,
                next_heartbeat_ms: 5_000,
                missed: 0,
            },
            Message::WorkProgress {
                node_name: "n1".to_string(),
                batch_id: 7,
                tested: 1000,
                hashes_sec: 12.5,
            },
            Message::AssignWork {
                worker_id: 1,
                batch_id: 7,
                work: WorkUnit {
                    job_id: 3,
                    attack_type: AttackType::BruteForce {
                        mask: "?u?l".to_string(),
                    },
                    targets: vec![TargetHash::new("MD5", "5D41402ABC4B2A76B9719D911017C592")],
                    keyspace_start: 0,
                    keyspace_end: 676,
                    keyspace_total: 676,
                },
            },
            Message::Wordlist {
                manifest: WordlistManifest::from_bytes("small.txt", b"a\nb\n"),
                words: vec!["a".to_string(), "b".to_string()],
            },
            Message::Shutdown {
                reason: "operator request".to_string(),
            },
            Message::Error {
                code: ErrorCode::Throttled,
                detail: "too many handshake attempts".to_string(),
            },
            Message::Result {
                node_name: "n1".to_string(),
                batch_id: 7,
                cracked: vec![CrackedEntry {
                    hash: "abc".to_string(),
                    password: "hello".to_string(),
                    algorithm: "MD5".to_string(),
                }],
                solved: vec![TargetHash::new("MD5", "abc")],
            },
        ]
    }

    #[test]
    fn every_variant_round_trips() {
        let cfg = bincode::config::standard();
        for m in samples() {
            let bytes = bincode::serde::encode_to_vec(&m, cfg)
                .unwrap_or_else(|e| panic!("{m:?} did not encode: {e}"));
            let (back, consumed): (Message, usize) =
                bincode::serde::decode_from_slice(&bytes, cfg)
                    .unwrap_or_else(|e| panic!("{m:?} did not decode: {e}"));
            assert_eq!(consumed, bytes.len(), "{m:?} did not consume the whole payload");
            assert_eq!(back, m);
        }
    }

    /// The variant list is the schema. This test names every one of them, so
    /// adding a variant makes it fail until the sample list is extended and the
    /// code is taught to handle it.
    #[test]
    fn the_sample_list_covers_every_variant() {
        assert_eq!(
            samples().len(),
            13,
            "a Message variant was added without a round trip sample"
        );
    }

    #[test]
    fn a_target_hash_is_lowercased_on_construction() {
        let t = TargetHash::new("md5", "5D41402ABC4B2A76B9719D911017C592");
        assert_eq!(t.hash, "5d41402abc4b2a76b9719d911017c592");
        assert_eq!(t.hash_type, "md5");
    }

    /// Two spellings of the same digest must be one target, or a chunk is built
    /// twice for a hash that is already cracked.
    #[test]
    fn targets_are_compared_case_insensitively() {
        let a = TargetHash::new("MD5", "5D41402ABC4B2A76B9719D911017C592");
        let b = TargetHash::new("MD5", "5d41402abc4b2a76b9719d911017c592");
        assert_eq!(a, b);
    }

    #[test]
    fn a_chunk_size_is_end_minus_start() {
        let wu = WorkUnit {
            job_id: 1,
            attack_type: AttackType::BruteForce { mask: "?d".into() },
            targets: vec![],
            keyspace_start: 100,
            keyspace_end: 110,
            keyspace_total: 1000,
        };
        assert_eq!(wu.total_size(), 10);
    }

    /// An inverted range is zero, not a huge number. `saturating_sub` makes an
    /// empty or reversed chunk harmless instead of wrapping into a full keyspace
    /// scan.
    #[test]
    fn a_reversed_chunk_is_empty_rather_than_enormous() {
        let wu = WorkUnit {
            job_id: 1,
            attack_type: AttackType::BruteForce { mask: "?d".into() },
            targets: vec![],
            keyspace_start: 100,
            keyspace_end: 10,
            keyspace_total: 1000,
        };
        assert_eq!(wu.total_size(), 0);
    }
}